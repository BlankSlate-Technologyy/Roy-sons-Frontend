export const getEquipmentByCategory = (categoryId) => {
  if (!categoryId || categoryId === "all") return HEALTHCARE_EQUIPMENT;
  return HEALTHCARE_EQUIPMENT.filter((item) => item.categoryId === categoryId);
};

export const getEquipmentBySlug = (slug) => {
  return HEALTHCARE_EQUIPMENT.find((item) => item.slug === slug) || null;
};

export const getRelatedEquipment = (equipment) => {
  if (!equipment) return [];
  if (equipment.relatedSlugs && equipment.relatedSlugs.length > 0) {
    const related = HEALTHCARE_EQUIPMENT.filter((item) =>
      equipment.relatedSlugs.includes(item.slug)
    );
    if (related.length > 0) return related.slice(0, 4);
  }
  // Fallback to same category
  return HEALTHCARE_EQUIPMENT.filter(
    (item) => item.categoryId === equipment.categoryId && item.id !== equipment.id
  ).slice(0, 4);
};

